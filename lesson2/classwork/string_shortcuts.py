first = "Sova"
last = "Coding"

# String concatenation
full = first + " " + last
print(full)  # Output: Sova Coding

# Repeat a string
print("ha" * 3)  # Output: 'hahaha'

# 'in' checks if something appears inside a string
sentence = "I like python"
print("python" in sentence)  # Output: True
print("java" in sentence)    # Output: False

# Escape characters
print("He said, \"hello\"")
print("He said, \'hello\'")
print("\\")

print("Line1\nLine2") # New line